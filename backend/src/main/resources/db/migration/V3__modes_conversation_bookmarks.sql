-- Additive only: existing sessions, questions, reports and skill scores are preserved.
ALTER TABLE interview_sessions ADD COLUMN mode VARCHAR(12) NOT NULL DEFAULT 'TECHNICAL';
ALTER TABLE questions ADD COLUMN follow_ups TEXT;             -- JSON: {"<expected concept>": "<predefined follow-up question>"}
ALTER TABLE candidate_profiles ADD COLUMN weekly_goal INT NOT NULL DEFAULT 3;

-- Conversation turns that are not already stored elsewhere (questions and first answers live in
-- interview_questions / candidate_answers). One follow-up and one reply per question at most.
CREATE TABLE interview_turns (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id            BIGINT NOT NULL REFERENCES interview_sessions (id) ON DELETE CASCADE,
    interview_question_id BIGINT NOT NULL REFERENCES interview_questions (id) ON DELETE CASCADE,
    kind                  VARCHAR(20) NOT NULL,   -- FOLLOW_UP | FOLLOW_UP_ANSWER
    source                VARCHAR(12) NOT NULL,   -- AI | RULE_BASED | CANDIDATE
    content               TEXT NOT NULL,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_turn_question_kind UNIQUE (interview_question_id, kind)
);
CREATE INDEX ix_turns_session ON interview_turns (session_id, id);

CREATE TABLE bookmarks (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    question_id BIGINT NOT NULL REFERENCES questions (id) ON DELETE CASCADE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_bookmark UNIQUE (user_id, question_id)
);
