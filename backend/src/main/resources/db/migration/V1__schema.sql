-- InterviewOS schema. Portable across PostgreSQL (runtime) and H2 in PostgreSQL mode (tests).
-- Deliberate denormalization (documented in docs/ARCHITECTURE.md):
--   interview_sessions.topics            CSV of selected topics (a filter-only attribute, never joined)
--   interview_questions.difficulty_at_selection / selection_reason   immutable audit trail of adaptation
--   interview_reports.report_json        immutable snapshot of the generated report
--   questions.options / rubric / test_cases   JSON text owned by one question

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    display_name  VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL DEFAULT 'USER',
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE UNIQUE INDEX uq_users_email ON users (email);   -- emails are stored lower-cased by AuthService

CREATE TABLE candidate_profiles (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT NOT NULL UNIQUE REFERENCES users (id) ON DELETE CASCADE,
    target_role       VARCHAR(30) NOT NULL,
    experience_level  VARCHAR(20) NOT NULL,
    skill_preferences VARCHAR(255) NOT NULL DEFAULT '',
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE questions (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code              VARCHAR(40)  NOT NULL UNIQUE,
    topic             VARCHAR(20)  NOT NULL,
    subtopic          VARCHAR(80)  NOT NULL,
    difficulty        VARCHAR(10)  NOT NULL,
    type              VARCHAR(10)  NOT NULL,
    statement         TEXT         NOT NULL,
    options           TEXT,
    answer_key        VARCHAR(10),
    explanation       TEXT,
    rubric            TEXT,
    test_cases        TEXT,
    time_estimate_sec INT          NOT NULL,
    version           INT          NOT NULL DEFAULT 1,
    active            BOOLEAN      NOT NULL DEFAULT TRUE
);
CREATE INDEX ix_questions_topic_diff ON questions (topic, difficulty, active);

CREATE TABLE question_tags (
    question_id BIGINT      NOT NULL REFERENCES questions (id) ON DELETE CASCADE,
    tag         VARCHAR(40) NOT NULL,
    PRIMARY KEY (question_id, tag)
);

CREATE TABLE interview_sessions (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    target_role        VARCHAR(30) NOT NULL,
    topics             VARCHAR(120) NOT NULL,
    base_difficulty    VARCHAR(10) NOT NULL,
    current_difficulty VARCHAR(10) NOT NULL,
    strong_streak      INT NOT NULL DEFAULT 0,
    weak_streak        INT NOT NULL DEFAULT 0,
    last_adjustment    VARCHAR(500),
    duration_minutes   INT NOT NULL,
    question_count     INT NOT NULL,
    status             VARCHAR(20) NOT NULL,
    started_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    deadline_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at       TIMESTAMP WITH TIME ZONE
);
CREATE INDEX ix_sessions_user_started ON interview_sessions (user_id, started_at DESC);
CREATE INDEX ix_sessions_user_status ON interview_sessions (user_id, status);

CREATE TABLE interview_questions (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id              BIGINT NOT NULL REFERENCES interview_sessions (id) ON DELETE CASCADE,
    question_id             BIGINT NOT NULL REFERENCES questions (id),
    position                INT    NOT NULL,
    difficulty_at_selection VARCHAR(10) NOT NULL,
    selection_reason        VARCHAR(1000) NOT NULL,
    presented_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_iq_session_question UNIQUE (session_id, question_id),
    CONSTRAINT uq_iq_session_position UNIQUE (session_id, position)
);

CREATE TABLE candidate_answers (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    interview_question_id BIGINT NOT NULL UNIQUE REFERENCES interview_questions (id) ON DELETE CASCADE,
    answer_text           TEXT,
    selected_option       VARCHAR(10),
    skipped               BOOLEAN NOT NULL DEFAULT FALSE,
    time_spent_sec        INT NOT NULL DEFAULT 0,
    submitted_at          TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE answer_evaluations (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    answer_id        BIGINT NOT NULL UNIQUE REFERENCES candidate_answers (id) ON DELETE CASCADE,
    score            DOUBLE PRECISION,
    correctness      VARCHAR(15) NOT NULL,
    strengths        TEXT NOT NULL,
    missing_concepts TEXT NOT NULL,
    feedback         TEXT NOT NULL,
    evaluator        VARCHAR(30) NOT NULL,
    finalized        BOOLEAN NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE skill_scores (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    topic      VARCHAR(20) NOT NULL,
    score      DOUBLE PRECISION NOT NULL,
    attempts   INT NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_skill_user_topic UNIQUE (user_id, topic)
);

CREATE TABLE evaluation_jobs (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind            VARCHAR(10) NOT NULL,
    ref_id          BIGINT NOT NULL,
    session_id      BIGINT NOT NULL REFERENCES interview_sessions (id) ON DELETE CASCADE,
    idempotency_key VARCHAR(80) NOT NULL UNIQUE,
    status          VARCHAR(12) NOT NULL,
    attempts        INT NOT NULL DEFAULT 0,
    last_error      TEXT,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_jobs_status_updated ON evaluation_jobs (status, updated_at);
CREATE INDEX ix_jobs_session ON evaluation_jobs (session_id);

CREATE TABLE interview_reports (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id    BIGINT NOT NULL UNIQUE REFERENCES interview_sessions (id) ON DELETE CASCADE,
    overall_score DOUBLE PRECISION NOT NULL,
    report_json   TEXT NOT NULL,
    ai_summary    TEXT,
    generated_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
